"""
ios/scripts/gen_theme.py
========================
Generate the iOS app's color tokens from ``styles.THEME``, the same registry
the web's CSS ``:root`` block and the Plotly theme read, so the phone and the
web can't drift on color.

    .venv/bin/python ios/scripts/gen_theme.py          # rewrite the Swift file
    .venv/bin/python ios/scripts/gen_theme.py --check  # exit 1 when it is stale

Every color token (hex or ``rgba(...)``) becomes a ``ThemeColor`` constant,
named in camelCase without the ``--cs-`` prefix (``--cs-win-bg`` ->
``winBg``). Geometry tokens in ``px`` become ``CGFloat`` points; font stacks
are skipped (the app uses the system font, which is what the web stack names).
``tests/test_theme_swift.py`` fails when this output is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = (ROOT / "ios" / "ChessDashboardKit" / "Sources" / "ChessDashboardKit" / "Theme"
       / "ThemeTokens.generated.swift")

_HEX = re.compile(r"^#([0-9a-fA-F]{6})$")
_RGBA = re.compile(r"^rgba\((\d+),(\d+),(\d+),([0-9.]+)\)$")
_PX = re.compile(r"^(\d+(?:\.\d+)?)px$")


def _name(token: str) -> str:
    parts = token.removeprefix("--cs-").split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def _alpha(text: str) -> str:
    value = float(text)
    return f"{value:g}"


def render(theme: dict[str, str]) -> str:
    colors: list[str] = []
    sizes: list[str] = []
    for token, value in theme.items():
        name = _name(token)
        if m := _HEX.match(value):
            h = m.group(1)
            r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
            colors.append(f"\tpublic static let {name} = ThemeColor(red: {r}, green: {g}, "
                          f"blue: {b}, alpha: 1)  // {token}: {value}")
        elif m := _RGBA.match(value):
            r, g, b, a = m.groups()
            colors.append(f"\tpublic static let {name} = ThemeColor(red: {r}, green: {g}, "
                          f"blue: {b}, alpha: {_alpha(a)})  // {token}: {value}")
        elif m := _PX.match(value):
            sizes.append(f"\tpublic static let {name}: CGFloat = {m.group(1)}  // {token}")
    lines = [
        "// GENERATED by ios/scripts/gen_theme.py from styles.THEME. Do not edit.",
        "// Regenerate: .venv/bin/python ios/scripts/gen_theme.py",
        "",
        "import CoreGraphics",
        "",
        "/// The web dashboard's theme tokens, one constant per `--cs-*` color.",
        "public enum Theme {",
        *colors,
        "}",
        "",
        "/// The web's geometry tokens, in points.",
        "public enum ThemeMetrics {",
        *sizes,
        "}",
    ]
    return "\n".join(lines) + "\n"


def current() -> str:
    sys.path.insert(0, str(ROOT))
    import styles

    return render(styles.THEME)


def main(argv: list[str]) -> int:
    swift = current()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != swift:
            print(f"{OUT.name} is stale: run ios/scripts/gen_theme.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text() != swift:
        OUT.write_text(swift)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
